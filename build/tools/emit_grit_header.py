"""Write grit rc_header stand-ins from .grd name attributes.

The in-tree grit tool is Python 2. Resource ids are assigned here (from 1000)
and must stay in lockstep with emit_resource_pak.py, which writes the pak
ResourceBundle loads at runtime.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

_NAME = re.compile(r'\bname="([A-Za-z0-9_]+)"')


def emit(grd: Path, dest_dir: Path) -> None:
    names = []
    seen = set()
    for match in _NAME.finditer(grd.read_text(encoding="utf-8", errors="replace")):
        name = match.group(1)
        if name in seen:
            continue
        seen.add(name)
        names.append(name)
    dest_dir.mkdir(parents=True, exist_ok=True)
    header = dest_dir / f"{grd.stem}.h"
    guard = "GRIT_" + grd.stem.upper() + "_H_"
    lines = [
        "// Generated by build/tools/emit_grit_header.py",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
    ]
    for index, name in enumerate(names, start=1000):
        lines.append(f"#define {name} {index}")
    lines.extend(["", f"#endif  // {guard}", ""])
    text = "\n".join(lines)
    header.write_text(text, encoding="utf-8", newline="\n")
    if grd.stem == "ui_resources":
        nested = dest_dir.parent / "ui" / "ui_resources" / "grit" / "ui_resources.h"
        nested.parent.mkdir(parents=True, exist_ok=True)
        nested.write_text(text, encoding="utf-8", newline="\n")


def main(argv: list[str]) -> int:
    if len(argv) < 3:
        print("usage: emit_grit_header.py <out-dir> <grd>...", file=sys.stderr)
        return 2
    dest = Path(argv[1])
    for raw in argv[2:]:
        emit(Path(raw), dest)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
